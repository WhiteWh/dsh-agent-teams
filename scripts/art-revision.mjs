#!/usr/bin/env node
/**
 * Content revision of the packaged artwork under `assets/agent-teams/`.
 *
 * The activity panel addresses its images by file name, and those names did not
 * change when the packs were redrawn (`member-engineer-v2.png` was the whale
 * and is now the amber terminal). A browser that cached the old bytes keeps
 * showing them for the whole `cache-control` lifetime, so the panel needs a URL
 * that changes with the content: `artwork.ts` appends `?v=<ART_REVISION>`.
 *
 * `src/client/art-revision.ts` is the committed home of that constant. It is
 * regenerated with `--write`, and both `pnpm build` and `scripts/verify.mjs`
 * compare it against the pack with `--check`, so a swapped icon cannot ship
 * under an old revision.
 *
 * Usage:
 *   node scripts/art-revision.mjs            print the computed and committed values
 *   node scripts/art-revision.mjs --check    fail when they differ (build/verify gate)
 *   node scripts/art-revision.mjs --write    regenerate src/client/art-revision.ts
 */
import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { sep } from 'node:path'
import { pathToFileURL } from 'node:url'

/** Packaged artwork directory whose bytes define the revision. */
export const ARTWORK_DIR = new URL('../assets/agent-teams/', import.meta.url)

/** Committed module carrying the revision the client appends to every URL. */
export const ART_REVISION_MODULE = new URL('../src/client/art-revision.ts', import.meta.url)

const REVISION_PATTERN = /export const ART_REVISION = '([0-9a-f]+)'/u

/**
 * Content revision of one artwork directory: every file name and its bytes, in
 * sorted order and length-framed so no byte can move between two entries.
 * @param dir - directory URL or path holding the `*.png` pack.
 * @returns twelve hex characters of the SHA-256 digest.
 */
export async function artworkRevision(dir = ARTWORK_DIR) {
  const base = dir instanceof URL ? dir : pathToFileURL(dir.endsWith(sep) ? dir : `${dir}${sep}`)
  const names = (await readdir(base)).filter(name => name.endsWith('.png')).sort()
  const hash = createHash('sha256')
  hash.update(`agent-teams-artwork\0${String(names.length)}\0`)
  for (const name of names) {
    const bytes = await readFile(new URL(name, base))
    hash.update(`${name}\0${String(bytes.length)}\0`)
    hash.update(bytes)
  }
  return hash.digest('hex').slice(0, 12)
}

/**
 * Revision currently committed in `src/client/art-revision.ts`.
 * @returns the hex revision, or undefined when the module is missing/unnamed.
 */
export async function committedArtworkRevision() {
  let source
  try {
    source = await readFile(ART_REVISION_MODULE, 'utf8')
  } catch {
    return undefined
  }
  return REVISION_PATTERN.exec(source)?.[1]
}

/** Source text of the generated revision module for one revision value. */
export function renderArtRevisionModule(revision) {
  return `/**
 * Content revision of \`assets/agent-teams/\`, generated by
 * \`node scripts/art-revision.mjs --write\` — do not edit by hand.
 *
 * Every artwork URL carries it as \`?v=\`, so redrawing a pack changes the URL
 * instead of leaving browsers on the previously cached bytes. \`pnpm build\` and
 * \`scripts/verify.mjs\` re-derive the value with \`--check\` and fail on a stale
 * constant, which is what keeps the pair honest.
 */
export const ART_REVISION = '${revision}'
`
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const computed = await artworkRevision()
  const committed = await committedArtworkRevision()
  const write = process.argv.includes('--write')
  const check = process.argv.includes('--check')
  if (write) {
    await writeFile(ART_REVISION_MODULE, renderArtRevisionModule(computed))
    console.log(`artwork revision written: ${computed}`)
  } else if (check) {
    if (committed !== computed) {
      console.error(`artwork revision is stale: committed ${committed ?? '(missing)'}, pack ${computed}`)
      console.error('run `node scripts/art-revision.mjs --write` and rebuild')
      process.exit(1)
    }
    console.log(`artwork revision: ${computed}`)
  } else {
    console.log(`pack=${computed}`)
    console.log(`committed=${committed ?? '(missing)'}`)
    if (committed !== computed) process.exitCode = 1
  }
}
